/**
 * Generates `THIRD_PARTY_LICENSES.txt` from the exact set of npm packages that esbuild
 * bundles into the shipped `dist/*.js` artifacts, so every bundled copyright notice and
 * permission text travels with the npm tarball (esbuild strips legal comments).
 *
 *   npm run licenses          # regenerate
 *   npm run licenses:check    # CI: fail when the file is stale or a license is not allowlisted
 */
import fs from 'node:fs';
import path from 'node:path';
import { build } from 'esbuild';

const root = path.resolve(import.meta.dirname, '..');
const outFile = path.join(root, 'THIRD_PARTY_LICENSES.txt');
const ALLOWED = new Set(['MIT', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', 'Apache-2.0', '(MPL-2.0 OR Apache-2.0)']);

const ENTRIES: Array<{ entry: string; platform: 'browser' | 'node'; artifact: string }> = [
  { entry: 'src/shell-entry.ts', platform: 'browser', artifact: 'dist/client.js' },
  { entry: 'src/plugin-entry.ts', platform: 'browser', artifact: 'dist/client.studio.js' },
  { entry: 'src/math-entry.ts', platform: 'browser', artifact: 'dist/math.js' },
  { entry: 'src/mermaid-entry.ts', platform: 'browser', artifact: 'dist/mermaid.js' },
  { entry: 'src/darkmode-entry.ts', platform: 'browser', artifact: 'dist/darkmode.js' },
  { entry: 'index.ts', platform: 'node', artifact: 'dist/index.js' },
];

interface PackageInfo {
  name: string;
  version: string;
  license: string;
  text: string;
  artifacts: Set<string>;
}

function packageRoot(input: string): string | null {
  const normalized = input.replace(/\\/g, '/');
  const marker = 'node_modules/';
  const at = normalized.lastIndexOf(marker);
  if (at < 0) return null;
  const parts = normalized.slice(at + marker.length).split('/');
  const name = parts[0].startsWith('@') ? parts[0] + '/' + parts[1] : parts[0];
  return path.resolve(root, normalized.slice(0, at) + marker + name);
}

function readLicenseText(dir: string): string {
  const normalizeEol = (value: string) => value.replace(/\r\n?/g, '\n').trim();
  const file = fs.readdirSync(dir).find((name) => /^(licen[sc]e|copying)(\.(md|txt))?$/i.test(name));
  if (file) return normalizeEol(fs.readFileSync(path.join(dir, file), 'utf8'));
  const readme = fs.readdirSync(dir).find((name) => /^readme(\.md)?$/i.test(name));
  if (readme) {
    const match = /^#+\s*License\s*$([\s\S]*?)(?=^#+\s|\s*$(?![\s\S]))/im.exec(
      fs.readFileSync(path.join(dir, readme), 'utf8'),
    );
    if (match?.[1].trim()) return normalizeEol(match[1]);
  }
  return '';
}

function detectLicense(pkg: { license?: unknown; licenses?: Array<{ type?: string }> }, text: string): string {
  if (typeof pkg.license === 'string') return pkg.license;
  if (pkg.license && typeof pkg.license === 'object' && 'type' in pkg.license) return String(pkg.license.type);
  if (Array.isArray(pkg.licenses) && pkg.licenses.length) return pkg.licenses.map((l) => l.type).join(' OR ');
  if (/The MIT License|Permission is hereby granted, free of charge/i.test(text)) return 'MIT';
  return 'UNKNOWN';
}

async function collect(): Promise<PackageInfo[]> {
  const packages = new Map<string, PackageInfo>();
  for (const target of ENTRIES) {
    const result = await build({
      entryPoints: [path.join(root, target.entry)],
      bundle: true,
      write: false,
      metafile: true,
      platform: target.platform,
      format: target.platform === 'node' ? 'esm' : 'cjs',
      target: target.platform === 'node' ? ['node20'] : ['es2020'],
      loader: { '.css': 'text' },
      logLevel: 'silent',
    });
    for (const input of Object.keys(result.metafile.inputs)) {
      const dir = packageRoot(input);
      if (!dir) continue;
      const pkg = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8')) as {
        name: string;
        version: string;
        license?: unknown;
        licenses?: Array<{ type?: string }>;
      };
      const existing = packages.get(pkg.name);
      if (existing) {
        existing.artifacts.add(target.artifact);
        continue;
      }
      const text = readLicenseText(dir);
      packages.set(pkg.name, {
        name: pkg.name,
        version: pkg.version,
        license: detectLicense(pkg, text),
        text,
        artifacts: new Set([target.artifact]),
      });
    }
  }
  return [...packages.values()].sort((a, b) => a.name.localeCompare(b.name));
}

function render(packages: PackageInfo[]): string {
  const rule = '-'.repeat(78);
  const header = [
    'THIRD-PARTY SOFTWARE LICENSES',
    '',
    'dsh-markdown-studio bundles the following open-source packages into its shipped',
    'artifacts (dist/*.js). Each package is listed with its version, SPDX license, the',
    'artifacts it is bundled into, and its full license text as published on npm.',
    'This file is generated by `npm run licenses`; do not edit it by hand.',
    '',
    `Total bundled packages: ${packages.length}`,
    '',
  ];
  const sections = packages.map((pkg) =>
    [
      rule,
      `${pkg.name}@${pkg.version}`,
      `License: ${pkg.license}`,
      `Bundled into: ${[...pkg.artifacts].sort().join(', ')}`,
      rule,
      '',
      pkg.text || `(No license text shipped with the package; licensed under ${pkg.license}.)`,
      '',
    ].join('\n'),
  );
  return header.join('\n') + '\n' + sections.join('\n');
}

const packages = await collect();
const rejected = packages.filter((pkg) => !ALLOWED.has(pkg.license) || !pkg.text);
if (rejected.length) {
  console.error('Bundled packages with a non-allowlisted license or missing license text:');
  for (const pkg of rejected) console.error(`  - ${pkg.name}@${pkg.version} [${pkg.license}]`);
  process.exit(1);
}
const content = render(packages);
if (process.argv.includes('--check')) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8').replace(/\r\n?/g, '\n') : '';
  if (current !== content) {
    console.error('THIRD_PARTY_LICENSES.txt is stale. Run `npm run licenses` and commit the result.');
    process.exit(1);
  }
  console.log(`THIRD_PARTY_LICENSES.txt is up to date (${packages.length} bundled packages, all allowlisted).`);
} else {
  fs.writeFileSync(outFile, content);
  console.log(
    `wrote THIRD_PARTY_LICENSES.txt (${packages.length} packages, ${(content.length / 1024).toFixed(1)} KiB)`,
  );
}
