function extractLocaleCandidate(raw: unknown): string {
  if (typeof raw === 'string') return raw;
  if (!raw || typeof raw !== 'object') return '';
  const record = raw as { active?: unknown; id?: unknown };
  if (typeof record.active === 'string') return record.active;
  return typeof record.id === 'string' ? record.id : '';
}

export function resolveActiveLocaleId(service: LocaleService | null): string {
  if (!service) return 'zh';
  try {
    return extractLocaleCandidate(service.getLocale()) || 'zh';
  } catch {
    return 'zh';
  }
}

export interface StudioLocaleController {
  t: (key: string) => string;
  lang: () => 'zh' | 'en';
  useLocaleRevision: () => number;
  registerWithHost: (locale: LocaleService) => () => void;
}

export function createStudioLocaleController(React: typeof ReactNamespace, namespace: string): StudioLocaleController {
  let localeService: LocaleService | null = null;
  let translate: ((key: string) => string) | null = null;

  function lang(): 'zh' | 'en' {
    return /^zh/i.test(resolveActiveLocaleId(localeService)) ? 'zh' : 'en';
  }

  function subscribe(callback: () => void): () => void {
    if (!localeService) return function () {};
    return localeService.subscribe(callback);
  }

  function getRevision(): number {
    if (!localeService) return 0;
    try {
      return localeService.getSnapshot().revision;
    } catch {
      return 0;
    }
  }

  function t(key: string): string {
    let value: string | null = null;
    if (translate) {
      try {
        value = translate(key);
      } catch {
        value = null;
      }
    }
    if (value && value !== key) return value;
    const dict = lang() === 'zh' ? UI_STRINGS_ZH : UI_STRINGS_EN;
    return dict[key] || UI_STRINGS_EN[key] || key;
  }

  function useLocaleRevision(): number {
    return useExternalStore(React, subscribe, getRevision);
  }

  function registerWithHost(locale: LocaleService): () => void {
    localeService = locale;
    const disposers: Array<() => void> = [];
    const ids: Record<string, Record<string, string>> = { en: UI_STRINGS_EN, zh: UI_STRINGS_ZH };
    try {
      locale.getSnapshot().locales.forEach(function (definition: { id: string }) {
        if (!ids[definition.id]) ids[definition.id] = /^zh/i.test(definition.id) ? UI_STRINGS_ZH : UI_STRINGS_EN;
      });
    } catch {
      /* keep base dictionaries */
    }
    for (const id of Object.keys(ids)) {
      try {
        const dispose = locale.register(namespace, id, ids[id]);
        if (typeof dispose === 'function') disposers.push(dispose);
      } catch {
        /* ignore hot-reload duplicate */
      }
    }
    try {
      translate = locale.bind(namespace);
    } catch {
      translate = null;
    }
    return function () {
      for (const dispose of disposers) {
        try {
          dispose();
        } catch {
          /* ignore */
        }
      }
    };
  }

  return { t, lang, useLocaleRevision, registerWithHost };
}
